// Package clidocs generates the Markdown reference documentation of the
// command line applications.
package clidocs

import (
	"fmt"
	"strings"

	"github.com/urfave/cli/v2"
)

// CommandName is the name of the hidden command which prints the reference
// documentation.
const CommandName = "docs"

// EnvVar documents an environment variable which is not bound to a flag.
type EnvVar struct {
	// Name is the name of the variable.
	Name string
	// Description tells what the variable is used for.
	Description string
}

// Command returns the hidden command which prints the reference
// documentation of the application newApp builds. The documentation is
// generated from a new application instead of the running one, because
// urfave/cli stores the values of the environment in the flags, which would
// otherwise end up as their defaults.
func Command(newApp func() *cli.App, env []EnvVar) *cli.Command {
	return &cli.Command{
		Name:   CommandName,
		Hidden: true,
		Usage:  "print the reference documentation in Markdown",
		Action: func(ctx *cli.Context) error {
			doc, err := Markdown(newApp(), env)
			if err != nil {
				return err
			}

			if _, err := fmt.Fprint(ctx.App.Writer, doc); err != nil {
				return fmt.Errorf("write documentation: %w", err)
			}

			return nil
		},
	}
}

// Markdown returns the reference documentation of app: the output of
// urfave/cli one heading level below a title, followed by the environment
// variables of the flags and env.
func Markdown(app *cli.App, env []EnvVar) (string, error) {
	restore := documentBoolDefaults(app)
	doc, err := app.ToMarkdown()

	restore()

	if err != nil {
		return "", fmt.Errorf("generate markdown: %w", err)
	}

	var b strings.Builder

	fmt.Fprintf(&b, "<!-- Code generated by %q, DO NOT EDIT. -->\n\n", app.Name+" "+CommandName)
	fmt.Fprintf(&b, "# %s command line reference\n\n", app.Name)
	b.WriteString(demoteHeadings(doc))
	b.WriteString(envVarsSection(app, env))

	return b.String(), nil
}

// boolDefaultFlag documents the default of a boolean flag in its usage.
// urfave/cli prints the defaults of the flags which take a value only, so the
// Markdown would not tell that a boolean flag is enabled by default.
type boolDefaultFlag struct {
	*cli.BoolFlag
}

// GetUsage returns the usage of the flag followed by its default.
func (f boolDefaultFlag) GetUsage() string {
	return fmt.Sprintf("%s (default: %s)", f.BoolFlag.GetUsage(), f.GetDefaultText())
}

// documentBoolDefaults replaces the boolean flags of app and its commands
// which default to true or have a default text with a boolDefaultFlag. The
// returned function puts the original flags back.
func documentBoolDefaults(app *cli.App) (restore func()) {
	var restores []func()

	replace := func(flags []cli.Flag) {
		for i, flag := range flags {
			boolFlag, ok := flag.(*cli.BoolFlag)
			if !ok || boolFlag.DisableDefaultText ||
				(!boolFlag.Value && boolFlag.DefaultText == "") {
				continue
			}

			restores = append(restores, func() { flags[i] = boolFlag })
			flags[i] = boolDefaultFlag{BoolFlag: boolFlag}
		}
	}

	var replaceCommands func([]*cli.Command)

	replaceCommands = func(commands []*cli.Command) {
		for _, command := range commands {
			replace(command.Flags)
			replaceCommands(command.Subcommands)
		}
	}

	replace(app.Flags)
	replaceCommands(app.Commands)

	return func() {
		for _, restore := range restores {
			restore()
		}
	}
}

// demoteHeadings moves the headings of doc one level down, so that the
// document has a single title, and drops repeated blank lines. Lines in
// fenced code blocks stay as they are.
func demoteHeadings(doc string) string {
	lines := strings.Split(strings.TrimRight(doc, "\n"), "\n")
	result := make([]string, 0, len(lines))
	inFence := false

	for _, line := range lines {
		switch {
		case strings.HasPrefix(line, "```"):
			inFence = !inFence
		case inFence:
		case strings.HasPrefix(line, "#"):
			line = "#" + line
		case line == "" && len(result) != 0 && result[len(result)-1] == "":
			continue
		}

		result = append(result, line)
	}

	return strings.Join(result, "\n") + "\n"
}

// flagEnvVar is an environment variable which sets a flag.
type flagEnvVar struct {
	name, flag, command string
}

// envVarsSection returns the section documenting the environment variables
// of the visible flags of app and env, or nothing if there are none.
func envVarsSection(app *cli.App, env []EnvVar) string {
	flagVars := collectFlagEnvVars(app.VisibleFlags(), "")
	flagVars = append(flagVars, collectCommandEnvVars(app.Commands, "")...)

	if len(flagVars) == 0 && len(env) == 0 {
		return ""
	}

	var b strings.Builder

	b.WriteString("\n## ENVIRONMENT VARIABLES\n")

	if len(flagVars) != 0 {
		b.WriteString("\nThe following variables set the default of a flag.\n\n")
		b.WriteString("| Variable | Flag | Command |\n| --- | --- | --- |\n")

		for _, v := range flagVars {
			command := v.command
			if command == "" {
				command = "(global)"
			}

			fmt.Fprintf(&b, "| `%s` | `--%s` | %s |\n", v.name, v.flag, command)
		}
	}

	if len(env) != 0 {
		b.WriteString("\nThe following variables are read at runtime.\n\n")
		b.WriteString("| Variable | Description |\n| --- | --- |\n")

		for _, v := range env {
			fmt.Fprintf(&b, "| `%s` | %s |\n", v.Name, v.Description)
		}
	}

	return b.String()
}

// collectCommandEnvVars returns the environment variables of the visible
// flags of the visible commands and their subcommands.
func collectCommandEnvVars(commands []*cli.Command, parent string) []flagEnvVar {
	var result []flagEnvVar

	for _, command := range commands {
		if command.Hidden {
			continue
		}

		name := strings.TrimSpace(parent + " " + command.Name)
		result = append(result, collectFlagEnvVars(command.VisibleFlags(), name)...)
		result = append(result, collectCommandEnvVars(command.Subcommands, name)...)
	}

	return result
}

// collectFlagEnvVars returns the environment variables of flags.
func collectFlagEnvVars(flags []cli.Flag, command string) []flagEnvVar {
	var result []flagEnvVar

	for _, flag := range flags {
		docFlag, ok := flag.(cli.DocGenerationFlag)
		if !ok {
			continue
		}

		for _, name := range docFlag.GetEnvVars() {
			result = append(result, flagEnvVar{name: name, flag: flag.Names()[0], command: command})
		}
	}

	return result
}
