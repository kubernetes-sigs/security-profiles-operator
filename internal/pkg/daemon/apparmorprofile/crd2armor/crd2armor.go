var appArmorTemplate = `
# Generated by https://github.com/kubernetes-sigs/security-profiles-operator, do not edit by hand.
#include <tunables/global>
profile {{.Name}} flags=({{.ProfileMode}},attach_disconnected,mediate_deleted) {
  #include <abstractions/base>

  # Executable rules
{{ if ne .Data.Executable nil }}{{ if ne .Data.Executable.AllowedExecutables nil }}
{{range $allowed := .Data.Executable.AllowedExecutables}}  {{path $allowed}} ixr,
{{end}}{{end}}
{{ if ne .Data.Executable.AllowedLibraries nil }}
{{range $allowedlib := .Data.Executable.AllowedLibraries}}  {{path $allowedlib}} mr,
{{end}}{{end}}{{end}}
  {{ if .AllowMount }}
  /sbin/fsck ixr,
  /sbin/fsck.ext4 ixr,
  {{end}}

  # Filesystem rules
{{ if ne .Data.Filesystem nil }}{{ if ne .Data.Filesystem.ReadOnlyPaths nil }}
{{range $readonly := .Data.Filesystem.ReadOnlyPaths}}  {{path $readonly}} r,
{{end}}
{{ if not .ComplainMode }}{{range $readonly := .Data.Filesystem.ReadOnlyPaths}}  deny {{path $readonly}} wlk,
{{end}}{{end}}{{end}}
{{ if ne .Data.Filesystem.WriteOnlyPaths nil }}
{{range $writeonly := .Data.Filesystem.WriteOnlyPaths}}  {{path $writeonly}} wlk,
{{end}}
{{ if not .ComplainMode }}{{range $writeonly := .Data.Filesystem.WriteOnlyPaths}}  deny {{path $writeonly}} r,
{{end}}{{end}}{{end}}
{{ if ne .Data.Filesystem.ReadWritePaths nil }}
{{range $readwrite := .Data.Filesystem.ReadWritePaths}}  {{path $readwrite}} rwlk,
{{end}}{{end}}{{end}}{{ if .Data.Ptrace }}

  # Ptrace rules{{range $rule := .Data.Ptrace}}
  ptrace ({{join $rule.Access ", "}}){{if $rule.Peer}} peer={{$rule.Peer}}{{end}},{{end}}{{end}}

  # Network rules
{{ if ne .Data.Network nil }}{{ if ne .Data.Network.AllowRaw nil }}
{{ if .Data.Network.AllowRaw}}  network raw,{{else}}{{ if not .ComplainMode }}  deny network raw,{{end}}
{{end}}{{end}}
{{if ne .Data.Network.AllowTCP nil }}
{{if .Data.Network.AllowTCP}}  network tcp,
{{end}}{{end}}{{if ne .Data.Network.AllowUDP nil }}
{{if .Data.Network.AllowUDP}}  network udp,
{{end}}{{end}}{{end}}

  # Capabilities rules
{{ if ne .Data.Capability nil}}{{range $cap := .Data.Capability.AllowedCapabilities}}  capability {{$cap}},
{{end}}{{end}}

  {{ if .AllowMount }}
  mount,
  remount,
  umount,
  {{end}}

  # Raw rules placeholder

  # Add default deny for known information leak/priv esc paths
{{ if not .ComplainMode }}
  deny @{PROC}/* w,   # deny write for all files directly in /proc (not in a subdir)
  deny @{PROC}/{[^1-9],[^1-9][^0-9],[^1-9s][^0-9y][^0-9s],[^1-9][^0-9][^0-9][^0-9]*}/** w,
  deny @{PROC}/sys/[^k]** w,  # deny /proc/sys except /proc/sys/k* (effectively /proc/sys/kernel)
  deny @{PROC}/sys/kernel/{?,??,[^s][^h][^m]**} w,  # deny everything except shm* in /proc/sys/kernel/
  deny @{PROC}/sysrq-trigger rwklx,
  deny @{PROC}/mem rwklx,
  deny @{PROC}/kmem rwklx,
  deny @{PROC}/kcore rwklx,
  deny /sys/firmware/efi/efivars/** rwklx,
{{end}}
}
`

var parsedAppArmorTemplate = template.Must(
	template.New("apparmor").
		Funcs(template.FuncMap{"path": quotePath, "join": strings.Join}).
		Parse(appArmorTemplate),
)

// quotePath quotes paths which contain spaces, as AppArmor would otherwise
// read them as separate tokens and reject the whole profile. Globbing and
// variables still work inside the quotes. The validation guarantees that a
// path cannot contain quotes itself.
func quotePath(path string) string {
	if strings.HasPrefix(path, "/") && strings.Contains(path, " ") {
		return `"` + path + `"`
	}

	return path
}

// ApparmorData validated apparmor data which gets interpolated into the apparmor template.
type ApparmorData struct {
	Name       string
	Executable *Executable
	Filesystem *FileSystem
	Capability *Capability
	Network    *Network
	Ptrace     []PtraceRule
}

// PtraceRule validated ptrace rule.
type PtraceRule struct {
	// Access is what the rule grants, like "read".
	Access []string
	// Peer limits the rule to the processes confined by matching profiles.
	Peer string
}

// Executable validated allowed executables and libraries.
type Executable struct {
	AllowedExecutables []string
	AllowedLibraries   []string
}

// FileSystem validated allowed file paths.
type FileSystem struct {
	ReadOnlyPaths  []string
	WriteOnlyPaths []string
	ReadWritePaths []string
}

// Network network flags.
type Network struct {
	AllowRaw bool
	AllowTCP bool
	AllowUDP bool
}

// Capability validated allowed capabilities.
type Capability struct {
	AllowedCapabilities []string
}

// Global chars constraints: these are strictly forbidden regardless of field type.
var (
	// Allowed characters in the profile name.
	profileNameChars = regexp.MustCompile(`^[a-zA-Z0-9_./-]+$`)
	// String regex for path validation in case of allowed executables and libraries.
	// Enforces that the path:
	// 1. Starts with a forward slash (must be an absolute path).
	// 2. Contains only safe characters: alphanumeric, slashes, dashes, dots, underscores, plus, and spaces.
	// 3. Allows AppArmor globbing (*, **, ?) if you intend to support wildcards.
	// 4. Allows Apparmor variables as: /proc/@{pid}/cgroup, and a literal @,
	//    for example in systemd template unit paths.
	// 5. A valid absolute path (including just "/")
	// Critically, it EXCLUDES commas, quotes, and newlines. Braces are only
	// allowed as part of a variable. Earlier releases accepted any brace,
	// but apparmor_parser rejects a brace group without a comma ("Invalid
	// number of items between {}") as well as an unbalanced brace, and
	// commas are rejected, so no profile with such a path ever loaded.
	// It has to match the validation of the API.
	strictPathRegex = regexp.MustCompile(`^/(?:[a-zA-Z0-9_./*?+@ -]|@\{[a-zA-Z0-9_]+\})*$`)

	// ptraceRuleRegex matches a ptrace rule in a list of filesystem paths or
	// of allowed executables and libraries. Before the API had a field for
	// ptrace rules, profiles, including the ones bundled with the operator,
	// put them there, optionally followed by a comment. They used to be
	// rendered like a path, which turned them into a "deny ptrace" rule in
	// enforce mode and into a parser error without the comment. The API
	// accepts them in the lists of executables and libraries as well. They
	// are taken out of the lists and rendered as ptrace rules. The ptrace
	// field replaces this form.
	ptraceRuleRegex = regexp.MustCompile(`^ptrace\s*\(([a-zA-Z]+)\),(?:\s*#.*)?$`)

	// ptracePeerRegex matches the peer of a ptrace rule. It has to match the
	// validation of the API.
	ptracePeerRegex = regexp.MustCompile(`^(?:[a-zA-Z0-9_./*?-]|@\{profile_name\})+$`)
)

// ptraceAccess are the accesses a ptrace rule can grant.
var ptraceAccess = map[string]bool{
	"r": true, "w": true, "rw": true,
	"read": true, "readby": true, "trace": true, "tracedby": true,
}

// ptraceRule returns the access of a ptrace rule put into a list of paths,
// and false if entry is no ptrace rule.
func ptraceRule(entry string) (string, bool) {
	match := ptraceRuleRegex.FindStringSubmatch(entry)
	if match == nil {
		return "", false
	}

	return strings.ToLower(match[1]), true
}

// DeprecatedPtraceRulesMessage is the warning for a profile for which
// UsesDeprecatedPtraceRules reports true.
const DeprecatedPtraceRulesMessage = "DEPRECATED: ptrace rules in spec.abstract.filesystem " +
	"and spec.abstract.executable paths will be removed in a future API version, " +
	"use spec.abstract.ptrace instead"

// UsesDeprecatedPtraceRules reports whether abstract puts ptrace rules into
// the lists of filesystem paths, executables or libraries instead of using
// the ptrace field.
func UsesDeprecatedPtraceRules(abstract *apparmorprofileapi.AppArmorAbstract) bool {
	if abstract == nil {
		return false
	}

	var entries []string

	if abstract.Filesystem != nil {
		entries = slices.Concat(
			abstract.Filesystem.ReadOnlyPaths,
			abstract.Filesystem.WriteOnlyPaths,
			abstract.Filesystem.ReadWritePaths,
		)
	}

	if abstract.Executable != nil {
		entries = slices.Concat(
			entries,
			abstract.Executable.AllowedExecutables,
			abstract.Executable.AllowedLibraries,
		)
	}

	for _, entry := range entries {
		if _, ok := ptraceRule(entry); ok {
			return true
		}
	}

	return false
}

// newPtraceRules returns the ptrace rules of the ptrace field followed by the
// ones put into the paths, which grant their access to every peer.
func newPtraceRules(
	rules *apparmorprofileapi.AppArmorPtraceRules,
	legacyAccess []string,
) []PtraceRule {
	var result []PtraceRule

	// A peer without any access is kept, so that the validation rejects it
	// instead of silently dropping the rule.
	if rules != nil && (len(rules.AllowedAccess) != 0 || rules.Peer != "") {
		access := make([]string, 0, len(rules.AllowedAccess))
		for _, a := range rules.AllowedAccess {
			access = append(access, string(a))
		}

		slices.Sort(access)
		result = append(result, PtraceRule{Access: slices.Compact(access), Peer: rules.Peer})
	}

	slices.Sort(legacyAccess)

	for _, access := range slices.Compact(legacyAccess) {
		result = append(result, PtraceRule{Access: []string{access}})
	}

	return result
}

// splitPtraceRules returns the paths without the ptrace rules and the access
// of those rules.
func splitPtraceRules(entries []string) (paths, access []string) {
	if entries == nil {
		return nil, nil
	}

	paths = make([]string, 0, len(entries))

	for _, entry := range entries {
		if a, ok := ptraceRule(entry); ok {
			access = append(access, a)

			continue
		}

		paths = append(paths, entry)
	}

	return paths, access
}

func newApparmorData(name string, abstract *apparmorprofileapi.AppArmorAbstract) *ApparmorData {
	data := &ApparmorData{
		Name: name,
	}
	if abstract == nil {
		return data
	}

	var legacyPtrace []string

	if abstract.Executable != nil {
		executables, executablesPtrace := splitPtraceRules(abstract.Executable.AllowedExecutables)
		libraries, librariesPtrace := splitPtraceRules(abstract.Executable.AllowedLibraries)

		data.Executable = &Executable{
			AllowedExecutables: executables,
			AllowedLibraries:   libraries,
		}

		legacyPtrace = slices.Concat(executablesPtrace, librariesPtrace)
	}

	if abstract.Filesystem != nil {
		readOnly, readOnlyPtrace := splitPtraceRules(abstract.Filesystem.ReadOnlyPaths)
		writeOnly, writeOnlyPtrace := splitPtraceRules(abstract.Filesystem.WriteOnlyPaths)
		readWrite, readWritePtrace := splitPtraceRules(abstract.Filesystem.ReadWritePaths)

		data.Filesystem = &FileSystem{
			ReadOnlyPaths:  readOnly,
			WriteOnlyPaths: writeOnly,
			ReadWritePaths: readWrite,
		}

		legacyPtrace = slices.Concat(legacyPtrace, readOnlyPtrace, writeOnlyPtrace, readWritePtrace)
	}

	data.Ptrace = newPtraceRules(abstract.Ptrace, legacyPtrace)

	if abstract.Capability != nil {
		data.Capability = &Capability{
			AllowedCapabilities: normalizeCapabilities(abstract.Capability.AllowedCapabilities),
		}
	}

	if abstract.Network != nil {
		data.Network = &Network{}
		if abstract.Network.AllowRaw != nil {
			data.Network.AllowRaw = *abstract.Network.AllowRaw
		}

		if abstract.Network.Protocols != nil &&
			abstract.Network.Protocols.AllowTCP != nil {
			data.Network.AllowTCP = *abstract.Network.Protocols.AllowTCP
		}

		if abstract.Network.Protocols != nil &&
			abstract.Network.Protocols.AllowUDP != nil {
			data.Network.AllowUDP = *abstract.Network.Protocols.AllowUDP
		}
	}

	return data
}

func (d *ApparmorData) Validate() error {
	// 1. Validate profile name (usually limited to [a-zA-Z0-9_-])
	if d.Name != "" && !profileNameChars.MatchString(d.Name) {
		return fmt.Errorf("invalid profile name: %q", d.Name)
	}

	// 2. Validates all file system paths
	if d.Filesystem != nil {
		paths := make([]string, 0,
			len(d.Filesystem.ReadOnlyPaths)+
				len(d.Filesystem.WriteOnlyPaths)+len(d.Filesystem.ReadWritePaths))
		paths = append(paths, d.Filesystem.ReadOnlyPaths...)
		paths = append(paths, d.Filesystem.WriteOnlyPaths...)
		paths = append(paths, d.Filesystem.ReadWritePaths...)

		for _, path := range paths {
			if err := validPath(path); err != nil {
				return fmt.Errorf("validating path: %w", err)
			}
		}
	}

	// 3. Validates all capabilities against an allowed list
	if d.Capability != nil {
		for _, cap := range d.Capability.AllowedCapabilities {
			if err := validateCapability(cap); err != nil {
				return fmt.Errorf("validating capability: %w", err)
			}
		}
	}

	// 4. Validates the ptrace rules.
	for _, rule := range d.Ptrace {
		if err := validatePtraceRule(rule); err != nil {
			return fmt.Errorf("validating ptrace rule: %w", err)
		}
	}

	// 5. Validates all allowed executables and libraries.
	if d.Executable != nil {
		execsAndLibs := make([]string, 0,
			len(d.Executable.AllowedExecutables)+len(d.Executable.AllowedLibraries))
		execsAndLibs = append(execsAndLibs, d.Executable.AllowedExecutables...)
		execsAndLibs = append(execsAndLibs, d.Executable.AllowedLibraries...)

		for _, exec := range execsAndLibs {
			if err := validateExecutableOrLibrary(exec); err != nil {
				return fmt.Errorf("validating execs and libs: %w", err)
			}
		}
	}

	return nil
}

func validatePtraceRule(rule PtraceRule) error {
	if len(rule.Access) == 0 {
		return errors.New("ptrace rule without access")
	}

	for _, access := range rule.Access {
		if !ptraceAccess[access] {
			return fmt.Errorf("invalid ptrace access: %q", access)
		}
	}

	if rule.Peer != "" && !ptracePeerRegex.MatchString(rule.Peer) {
		return fmt.Errorf("invalid ptrace peer: %q", rule.Peer)
	}

	return nil
}

func validPath(path string) error {
	// An empty path would be rendered as a rule without a path.
	if !strictPathRegex.MatchString(path) {
		return fmt.Errorf("path must contain only safe characters: %q", path)
	}

	return nil
}

// normalizeCapabilities returns the capabilities in the lower case form
// without surrounding whitespace which AppArmor expects. Profiles stored
// before the API rejected other spellings may still contain them.
func normalizeCapabilities(capabilities []string) []string {
	if capabilities == nil {
		return nil
	}

	normalized := make([]string, 0, len(capabilities))
	for _, capability := range capabilities {
		normalized = append(normalized, strings.ToLower(strings.TrimSpace(capability)))
	}

	return normalized
}

func validateCapability(capability string) error {
	// Contains all standard Linux capabilities supported by AppArmor.
	// They are matched in lowercase, without the "CAP_" prefix.
	validCapabilities := map[string]bool{
		"chown": true, "dac_override": true, "dac_read_search": true,
		"fowner": true, "fsetid": true, "kill": true, "setgid": true,
		"setuid": true, "setpcap": true, "linux_immutable": true,
		"net_bind_service": true, "net_broadcast": true, "net_admin": true,
		"net_raw": true, "ipc_lock": true, "ipc_owner": true,
		"sys_module": true, "sys_rawio": true, "sys_chroot": true,
		"sys_ptrace": true, "sys_pacct": true, "sys_admin": true,
		"sys_boot": true, "sys_nice": true, "sys_resource": true,
		"sys_time": true, "sys_tty_config": true, "mknod": true,
		"lease": true, "audit_write": true, "audit_control": true,
		"setfcap": true, "mac_override": true, "mac_admin": true,
		"syslog": true, "wake_alarm": true, "block_suspend": true,
		"audit_read": true, "perfmon": true, "bpf": true, "checkpoint_restore": true,
	}

	normalized := strings.ToLower(strings.TrimSpace(capability))
	if exists, ok := validCapabilities[normalized]; ok && exists {
		return nil
	}

	return fmt.Errorf("invalid or forbidden capability: %q", capability)
}

func validateExecutableOrLibrary(path string) error {
	// An empty path would be rendered as a rule without a path.
	if !strictPathRegex.MatchString(path) {
		return fmt.Errorf("path must be absolute and contain only safe characters: %q", path)
	}

	if strings.Contains(path, "/../") || strings.HasPrefix(path, "/..") {
		return fmt.Errorf("path cannot contain directory traversal: %q", path)
	}

	return nil
}

type apparmorTemplateArgs struct {
	Name         string
	ProfileMode  string
	ComplainMode bool
	AllowMount   bool
	Data         *ApparmorData
}

// GenerateProfile uses the CRD representation of an abstracted profile to generate a
// full AppArmor profile.
func GenerateProfile(
	name string,
	mode apparmorprofileapi.AppArmorMode,
	abstract *apparmorprofileapi.AppArmorAbstract,
) (string, error) {
	var generated bytes.Buffer

	// This is a bit of a hack to allow containers that exercise raw I/O to use `mount`.
	// Eventually we should get rid of this and record mount/umount properly.
	allowMount := (abstract != nil &&
		abstract.Capability != nil &&
		abstract.Capability.AllowedCapabilities != nil &&
		slices.Contains(normalizeCapabilities(abstract.Capability.AllowedCapabilities), "sys_rawio"))

	if abstract == nil {
		return "", errors.New("abstract cannot be nil")
	}

	// Make sure that the data provided as input is valid and doesn't contain malicious content.
	data := newApparmorData(name, abstract)
	if err := data.Validate(); err != nil {
		return "", fmt.Errorf("validating data injected into apparmor profile: %w", err)
	}

	complain := mode == apparmorprofileapi.AppArmorModeComplain
	templateArgs := apparmorTemplateArgs{
		Name:         name,
		Data:         data,
		ProfileMode:  profileMode(mode),
		ComplainMode: complain,
		AllowMount:   allowMount,
	}

	if err := parsedAppArmorTemplate.Execute(&generated, templateArgs); err != nil {
		return "", err
	}

	return generated.String(), nil
}

func profileMode(mode apparmorprofileapi.AppArmorMode) string {
	if mode == apparmorprofileapi.AppArmorModeComplain {
		return "complain"
	}

	return "enforce"
}
