// TestCommandFlagNamesAreUnique guards against a duplicate flag name or alias
// within a command, which urfave/cli only reports by panicking when the
// command runs.
func TestCommandFlagNamesAreUnique(t *testing.T) {
	t.Parallel()

	var assertCommand func(t *testing.T, command *cli.Command)

	assertCommand = func(t *testing.T, command *cli.Command) {
		t.Helper()

		seen := map[string]bool{}

		for _, flag := range command.Flags {
			for _, name := range flag.Names() {
				require.False(
					t, seen[name],
					"flag %q defined more than once for command %q", name, command.Name,
				)

				seen[name] = true
			}
		}

		for _, subCommand := range command.Subcommands {
			assertCommand(t, subCommand)
		}
	}

	for _, command := range newApp().Commands {
		assertCommand(t, command)
	}
}

// TestPlatformFlagsAreConsistent guards that push and pull accept the same
// spellings of the platform flag, which used to differ.
func TestPlatformFlagsAreConsistent(t *testing.T) {
	t.Parallel()

	flagNames := func(t *testing.T, commandName string) map[string]bool {
		t.Helper()

		names := map[string]bool{}

		for _, command := range newApp().Commands {
			if command.Name != commandName {
				continue
			}

			for _, flag := range command.Flags {
				for _, name := range flag.Names() {
					names[name] = true
				}
			}
		}

		require.NotEmpty(t, names, commandName)

		return names
	}

	for _, commandName := range []string{"push", "pull"} {
		names := flagNames(t, commandName)
		require.True(t, names["p"], commandName)
		require.True(t, names["platform"], commandName)
		require.True(t, names["platforms"], commandName)
		require.True(t, names["s"], commandName)
	}
}

// TestProfileFlagIsConsistent guards that the commands which read profiles
// from a flag accept the same spelling of it.
func TestProfileFlagIsConsistent(t *testing.T) {
	t.Parallel()

	for _, command := range newApp().Commands {
		if command.Name != "run" && command.Name != "push" {
			continue
		}

		found := false

		for _, flag := range command.Flags {
			found = found || slices.Contains(flag.Names(), "profile")
		}

		require.True(t, found, command.Name)
	}
}

// TestCommandsAreDocumented guards that every visible command explains itself
// in its help beyond the one line usage.
func TestCommandsAreDocumented(t *testing.T) {
	t.Parallel()

	for _, command := range newApp().Commands {
		if command.Hidden || command.Name == "version" {
			continue
		}

		require.NotEmpty(t, command.Usage, command.Name)
		require.NotEmpty(t, command.Description, command.Name)
		require.NotEmpty(t, command.ArgsUsage, command.Name)
	}
}

// TestPrivilegedFlag guards that both commands which run a command can keep
// the sudo privileges.
func TestPrivilegedFlag(t *testing.T) {
	t.Parallel()

	for _, command := range newApp().Commands {
		if command.Name != "record" && command.Name != "run" {
			continue
		}

		found := false

		for _, flag := range command.Flags {
			found = found || flag.Names()[0] == "privileged"
		}

		require.True(t, found, command.Name)
	}
}

func TestDocsCommand(t *testing.T) {
	t.Parallel()

	var out bytes.Buffer

	app := newApp()
	app.Writer = &out

	require.NoError(t, app.Run([]string{"spoc", clidocs.CommandName}))
	require.True(t, strings.HasPrefix(out.String(), "<!-- Code generated by \"spoc docs\""))
	require.Contains(t, out.String(), "\n# spoc command line reference\n")
	require.Contains(t, out.String(), "\n### pull, l\n")
	require.Contains(t, out.String(), "| `SPOC_KEY` | `--key` | pull |\n")
	require.Contains(t, out.String(), "\n### sign\n")
	require.Contains(t, out.String(), "| `SIGSTORE_ID_TOKEN` |")

	// The SPOC_ prefixed variables come first, the former names still work.
	for flag, envVars := range map[string][]string{
		"disable-signature-verification": {
			"SPOC_DISABLE_SIGNATURE_VERIFICATION", "DISABLE_SIGNATURE_VERIFICATION",
		},
		"allowed-identity-regexp": {"SPOC_ALLOWED_IDENTITY_REGEXP", "ALLOWED_IDENTITIES_REGEXP"},
		"allowed-oidc-issuer-regexp": {
			"SPOC_ALLOWED_OIDC_ISSUER_REGEXP", "ALLOWED_OIDC_ISSUER_REGEXP",
		},
	} {
		for _, envVar := range envVars {
			require.Contains(t, out.String(), "| `"+envVar+"` | `--"+flag+"` | pull |\n")
		}

		require.Less(
			t,
			strings.Index(out.String(), "`"+envVars[0]+"`"),
			strings.Index(out.String(), "`"+envVars[1]+"`"),
		)
	}

	require.Contains(t, out.String(), "| `"+spocli.EnvKeyUsername+"` |")
	require.NotContains(t, out.String(), "### docs")
}

func TestMergeError(t *testing.T) {
	t.Parallel()

	var exitErr cli.ExitCoder

	err := mergeError(merger.ErrBaseProfileOutdated)
	require.ErrorAs(t, err, &exitErr)
	require.Equal(t, exitCodeBaseProfileOutdated, exitErr.ExitCode())

	errOther := errors.New("broken")

	err = mergeError(errOther)
	require.ErrorIs(t, err, errOther)
	require.NotErrorAs(t, err, &exitErr)
}
